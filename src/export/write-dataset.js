import { readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import { DatabaseSync } from 'node:sqlite';

import { LOAD_ORDER, schemaColumns } from '../db/database.js';
import { computeMetrics } from '../derive/metrics.js';
import { POLICY } from '../domain/rules.js';
import { generateDataset } from '../generator/index.js';
import { writeCsvTables } from './csv-export.js';
import { sha256File, writeJsonTables, writeSqlSeed, writeSqliteDatabase } from './formats.js';
import { writeGroundTruth } from './ground-truth.js';
import { writeMetrics } from './reports.js';

const PACKAGE = JSON.parse(readFileSync(new URL('../../package.json', import.meta.url), 'utf8'));
export const DATABASE_FILE = 'sqlite/yottashift.db';

function sqliteVersion() {
  const db = new DatabaseSync(':memory:');
  const { v } = db.prepare('SELECT sqlite_version() AS v').get();
  db.close();
  return v;
}

/** Facts about the machine that produced the files; the SQLite file's bytes depend on them. */
export function environment() {
  return { node: process.versions.node, sqlite: sqliteVersion() };
}

function buildManifest({ config, profileName, dataset, dir, files }) {
  const byType = {};
  for (const label of dataset.groundTruth)
    byType[label.issue_type] = (byType[label.issue_type] ?? 0) + 1;
  return {
    dataset: 'YottaShift — synthetic workforce-scheduling data',
    profile: profileName,
    seed: config.seed,
    command: `npm run generate -- --profile ${profileName}`,
    generator: { name: PACKAGE.name, version: PACKAGE.version },
    config_sha256: createHash('sha256').update(JSON.stringify(config)).digest('hex'),
    environment: environment(),
    window: {
      start_date: dataset.window.startDate,
      end_date: dataset.window.endDate,
      days: dataset.window.days,
      snapshot_at: dataset.window.snapshotAt,
    },
    volumes: dataset.profile,
    tables: Object.fromEntries(dataset.tables.map(([name, rows]) => [name, rows.length])),
    ground_truth: {
      anomalies: dataset.groundTruth.filter((l) => l.label_class === 'ANOMALY').length,
      boundary_cases: dataset.groundTruth.filter((l) => l.label_class === 'BOUNDARY').length,
      by_issue_type: byType,
    },
    provenance: {
      source: 'Synthetic: every record is generated by this repository from the seed above',
      external_data: 'none',
      personal_data: 'none — names are random combinations of common given names and surnames',
      reference_inspiration:
        'Holiday calendar modelled on common Indian public holidays (dates of moveable festivals approximate; not an authoritative list)',
      licence: 'Released with the repository',
    },
    policy: POLICY,
    files: files.map((f) => {
      const path = join(dir, f.path);
      return { ...f, bytes: statSync(path).size, sha256: sha256File(path) };
    }),
  };
}

export function exportDataset({ config, profileName, outDir }) {
  const dataset = generateDataset(config, profileName);
  const dir = join(outDir, profileName);
  const columns = schemaColumns();
  const columnsOf = (table) => columns.get(table);

  // The database is written first: loading it enforces the schema, so a bad row stops the run
  // before any other file is touched.
  const databasePath = join(dir, DATABASE_FILE);
  try {
    writeSqliteDatabase(databasePath, dataset.tables);
  } catch (error) {
    rmSync(databasePath, { force: true });
    throw error;
  }
  writeCsvTables(join(dir, 'csv'), dataset.tables, columnsOf);
  writeJsonTables(join(dir, 'json'), dataset.tables, columnsOf);
  writeSqlSeed(join(dir, 'sql', 'seed.sql'), dataset.tables, columnsOf, {
    profileName,
    seed: config.seed,
  });
  writeGroundTruth(join(dir, 'ground_truth'), dataset.groundTruth);
  const metrics = computeMetrics(Object.fromEntries(dataset.tables), {
    patterns: config.operatingPatterns,
    window: dataset.window,
  });
  writeMetrics(join(dir, 'reports'), metrics, { profileName, seed: config.seed });

  const rows = Object.fromEntries(dataset.tables.map(([name, list]) => [name, list.length]));
  const files = [
    ...LOAD_ORDER.map((table) => ({
      path: `csv/${table}.csv`,
      format: 'csv',
      table,
      rows: rows[table],
    })),
    ...LOAD_ORDER.map((table) => ({
      path: `json/${table}.json`,
      format: 'json',
      table,
      rows: rows[table],
    })),
    {
      path: 'sql/seed.sql',
      format: 'sql',
      table: null,
      rows: Object.values(rows).reduce((a, b) => a + b, 0),
    },
    {
      path: DATABASE_FILE,
      format: 'sqlite',
      table: null,
      rows: Object.values(rows).reduce((a, b) => a + b, 0),
    },
    {
      path: 'ground_truth/ground_truth.csv',
      format: 'csv',
      table: null,
      rows: dataset.groundTruth.length,
    },
    {
      path: 'ground_truth/ground_truth.json',
      format: 'json',
      table: null,
      rows: dataset.groundTruth.length,
    },
    { path: 'reports/metrics.json', format: 'json', table: null, rows: null },
    { path: 'reports/metrics.md', format: 'markdown', table: null, rows: null },
  ];
  const manifest = buildManifest({ config, profileName, dataset, dir, files });
  writeFileSync(join(dir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
  return { dataset, metrics, manifest, dir };
}
